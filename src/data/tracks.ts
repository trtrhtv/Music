import { list, p, tip, type Block } from './blocks';
import { CH, STRUMS, notesTab, tabFrom } from './guitarLib';

/**
 * The guitar program: four tracks practised side by side, each in stages.
 * A stage is passed by its test – on two different days – not by the calendar.
 */

export type TrackId = 'tech' | 'rhythm' | 'neck' | 'finger';

export interface Exercise {
  id: string;
  title: string;
  steps: string[];
  content?: Block[];
  /** Daily variations of the same exercise (same difficulty), so repetition doesn't get stale. */
  vary?: string[];
  /** BPM (or chord changes per minute) to log while practising. */
  bpm?: { start: number; target: number; unit?: 'changes' };
  /** What you need to know first, explained from zero – shown above the steps – and where to learn more. */
  basics?: string[];
  learn?: { label: string; to: string }[];
}

export interface Stage {
  title: string;
  /** What you can do when the stage is done – one line. */
  goal: string;
  exercises: Exercise[];
  /** The pass test: concrete and measurable. */
  test: string;
  /** Optional mic check of steadiness for the test: tempo and notes per beat. */
  timing?: { bpm: number; sub: number };
  /** Optional mic check that the test's notes are right: tabs played one after another. */
  check?: string[][];
}

export interface Track { id: TrackId; title: string; icon: string; desc: string; /** Glossary entries that explain this track's words. */ help: string[]; stages: Stage[] }

