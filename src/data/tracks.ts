const strum = (id: keyof typeof STRUMS, names: string[], bpm = 70, note?: string): Block => ({
  t: 'strum', name: STRUMS[id].name, rhythm: STRUMS[id].rhythm, bpm, chords: names.map((n) => CH[n]), chordNames: names, note: note ?? STRUMS[id].desc,
});
const metro = (bpm: number): Block => ({ t: 'metronome', bpm });
const tab = (title: string, lines: string[]): Block => ({ t: 'tab', title, lines });
const chordsOf = (...items: [string, number[]][]): Block => ({ t: 'chords', items: items.map(([name, frets]) => ({ name, frets })) });
const ch = (...names: string[]): Block => chordsOf(...names.map((n) => [n, CH[n]] as [string, number[]]));

/** One figure (e.g. "5h7p5") played on every string from 6 to 1. */
function figureOnStrings(figure: string, strings = [6, 5, 4, 3, 2, 1]): string[] {
  const w = figure.length + 1;
  const lines = Array.from({ length: 6 }, () => '-');
  for (const s of strings) for (let i = 0; i < 6; i++) lines[i] += i === s - 1 ? figure + '-' : '-'.repeat(w);
  return lines;
}
