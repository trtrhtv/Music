/** The item of a category for a given practice day, at the player's level. */
export function itemFor(cat: DailyCat, level: number, day: number): DailyItem {
  const lv = cat.levels[Math.min(level, cat.levels.length - 1)];
  return lv.items[day % lv.items.length];
}

