/**
 * The daily practice list: the same categories every day (the base), with what's played in each
 * rotating from day to day, and a level per category that moves on only when the player says so.
 *
 * Every item says in one line what to play; "how" has the steps; "first" explains every new word
 * from zero and is shown open the first time the item comes up.
 */

export interface DailyItem {
  id: string;
  /** One line: exactly what to play. */
  title: string;
  how: string[];
  /** Explained from zero – shown open the first time. */
  first?: string[];
  content?: Block[];
}
export interface DailyLevel { name: string; items: DailyItem[] }
export type DailyCatId = 'warm' | 'scales' | 'chords' | 'hand' | 'neck' | 'rhythm' | 'flamenco' | 'romanza' | 'song';
export interface DailyCat { id: DailyCatId; icon: string; title: string; min: number; hour: 1 | 2; why: string; levels: DailyLevel[] }

/* ───────── helpers ───────── */
const tab = (title: string, lines: string[], sub?: number): Block => ({ t: 'tab', title, lines, sub });
const metro = (bpm: number): Block => ({ t: 'metronome', bpm });
const chords = (...names: (string | [string, number[]])[]): Block => ({ t: 'chords', items: names.map((n) => (typeof n === 'string' ? { name: n, frets: CH[n] } : { name: n[0], frets: n[1] })) });
const strum = (r: Rhythm, name: string, names: string[], bpm: number, note?: string): Block => ({ t: 'strum', name, rhythm: r, bpm, chords: names.map((n) => CH[n] ?? EXTRA[n]), chordNames: names, note });
const S = (id: keyof typeof STRUMS) => STRUMS[id].rhythm;
const go = (...items: [string, string][]): Block => ({ t: 'go', items: items.map(([label, to]) => ({ label, to })) });
const at = (string: number, f: number, label?: string) => ({ s: 6 - string, f, label });

